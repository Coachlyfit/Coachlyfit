import { z } from "zod";
import type { SupabaseClient } from "@supabase/supabase-js";
import type { Database } from "@/lib/supabase/database.types";
import { subscriptionDisplayStatus, type ClientSubscriptionStatus } from "@/domain/billing/client-subscription";
import { VOICE_MIME_EXT, VOICE_NOTES_BUCKET, type VoiceMime } from "./voice-notes";

/** Counted by Unicode scalar value ("characters") so an emoji counts as one,
 * not as the two UTF-16 code units (or four UTF-8 bytes) it occupies. */
export const MESSAGE_MAX_BODY_CHARS = 2000;

/** Validation for sending a message. Kept in the domain layer (not the
 * Server Action) so it can be tested and reused. */
export const sendMessageSchema = z.object({
  clientId: z.string().uuid(),
  body: z.string()
    .trim()
    .min(1, { message: "message_required" })
    .refine(
      (text) => [...text].length <= MESSAGE_MAX_BODY_CHARS,
      { message: "message_too_long" },
    ),
  id: z.string().uuid().optional(),
});

type Message = Database["public"]["Tables"]["messages"]["Row"];
// last_read_at was added to the view in 20261008000002. Optional so this
// still type-checks (and the list still loads, minus the "not read yet"
// filter) against a database that hasn't had that migration applied.
type InboxThreadRow = Database["public"]["Views"]["coach_inbox_threads"]["Row"] & { last_read_at?: string | null };

// Supabase's generated view types mark every column nullable (views carry no
// NOT NULL metadata), but client_id/coach_id/display_name/status/unread_count
// are guaranteed non-null by the underlying clients columns and the view's
// own `coalesce(..., 0)`. Only the last-message columns are genuinely
// nullable (a client with no messages yet). Narrow once here so every
// consumer isn't re-checking columns that can't actually be null.
export type InboxThread = {
  client_id: string;
  coach_id: string;
  display_name: string;
  avatar_url: string | null;
  status: InboxThreadRow["status"];
  last_body: string | null;
  /** A voice note has an empty body; the list shows a label instead. */
  last_is_voice: boolean;
  last_sender_role: "coach" | "client" | null;
  last_message_at: string | null;
  unread_count: number;
  /** The coach sent the last message and the client hasn't opened it yet. */
  awaiting_read: boolean;
};

export type SendMessageInput = {
  /** Generated by the sender so the optimistic bubble and the stored row are
   * the same message, and a retry can't insert it twice. */
  id?: string;
  sender_role: "coach" | "client";
  body: string;
};

export type SendVoiceInput = {
  /** Required, unlike a text message's: the file is stored under it. */
  id: string;
  sender_role: "coach" | "client";
  file: Blob;
  mime: VoiceMime;
  durationSec: number;
};

export type ThreadPage = { messages: Message[]; hasMore: boolean };

export type BroadcastAudience = "all" | "subscribed";

export const THREAD_PAGE_SIZE = 30;
const UNIQUE_VIOLATION = "23505";
const STORAGE_ALREADY_EXISTS = "409";
const VOICE_URL_TTL_SECONDS = 300;

/** One thread per client — coach and client both read/write their own
 * thread (RLS: coach_rw + client_rw, both full-CRUD, unlike the checkins
 * one-sided coach_read/client_own split). coach_id/client_id are supplied
 * by the caller (a route/action that already resolved the current user's
 * own identity), same shape as ProgressService.submitCheckin — never
 * trusted from arbitrary request input beyond that resolved identity. */
export class MessagesService {
  constructor(private db: SupabaseClient<Database>) {}

  /** Inbox summary: one row per active client, via the coach_inbox_threads
   * view (last message + unread count precomputed in SQL, not N+1 queries).
   * Sorted unread-first, then most-recently-active, then name — a coach's
   * attention should land on what needs a reply, not just what's newest. */
  async listInbox(): Promise<InboxThread[]> {
    const { data, error } = await this.db.from("coach_inbox_threads").select("*").eq("status", "active");
    if (error) throw error;
    const threads: InboxThread[] = (data as InboxThreadRow[]).map((row) => ({
      client_id: row.client_id as string,
      coach_id: row.coach_id as string,
      display_name: row.display_name as string,
      avatar_url: row.avatar_url as string | null,
      status: row.status,
      last_body: row.last_body,
      last_is_voice: row.last_kind === "voice",
      last_sender_role: row.last_sender_role as "coach" | "client" | null,
      last_message_at: row.last_message_at,
      unread_count: row.unread_count ?? 0,
      awaiting_read: row.last_sender_role === "coach" && row.last_message_at != null && row.last_read_at === null,
    }));
    return threads.sort((a, b) => {
      if ((a.unread_count > 0) !== (b.unread_count > 0)) return a.unread_count > 0 ? -1 : 1;
      const aTime = a.last_message_at ? new Date(a.last_message_at).getTime() : 0;
      const bTime = b.last_message_at ? new Date(b.last_message_at).getTime() : 0;
      if (aTime !== bTime) return bTime - aTime;
      return a.display_name.localeCompare(b.display_name);
    });
  }

  /** One page of a thread, newest page first: without `before` the latest
   * messages, with it the page just older than that timestamp. Rows come
   * back oldest-to-newest (render order) however they were fetched. */
  async listThreadPage(clientId: string, opts: { before?: string | null; limit?: number } = {}): Promise<ThreadPage> {
    const limit = opts.limit ?? THREAD_PAGE_SIZE;
    let query = this.db.from("messages").select("*").eq("client_id", clientId);
    if (opts.before) query = query.lt("created_at", opts.before);
    // One extra row answers "is there an older page?" without a count query.
    const { data, error } = await query.order("created_at", { ascending: false }).limit(limit + 1);
    if (error) throw error;
    return { messages: data.slice(0, limit).reverse(), hasMore: data.length > limit };
  }

  async send(coachId: string, clientId: string, input: SendMessageInput): Promise<void> {
    const { error } = await this.db.from("messages").insert({ coach_id: coachId, client_id: clientId, ...input });
    // A retry of a send whose first attempt did land (the response was lost,
    // not the insert) hits the primary key -- that message is already sent.
    if (error && !(input.id && error.code === UNIQUE_VIOLATION)) throw error;
  }

  /** File first, row second, so the other side never receives a voice note
   * whose file isn't there yet. Both steps are safe to repeat under the same
   * id: a retry finds the file (or the row) already in place and carries on.
   * A file whose row never lands is removed by the voice-notes-cleanup cron. */
  async sendVoice(coachId: string, clientId: string, relationshipId: string, input: SendVoiceInput): Promise<void> {
    const path = `${relationshipId}/${input.id}.${VOICE_MIME_EXT[input.mime]}`;
    const { error: uploadError } = await this.db.storage
      .from(VOICE_NOTES_BUCKET)
      .upload(path, input.file, { contentType: input.mime, upsert: false });
    if (uploadError && (uploadError as { statusCode?: string }).statusCode !== STORAGE_ALREADY_EXISTS) throw uploadError;

    const { error } = await this.db.from("messages").insert({
      id: input.id,
      coach_id: coachId,
      client_id: clientId,
      sender_role: input.sender_role,
      kind: "voice",
      body: "",
      audio_path: path,
      audio_mime: input.mime,
      audio_duration_sec: input.durationSec,
      audio_size_bytes: input.file.size,
    });
    if (error && error.code !== UNIQUE_VIOLATION) throw error;
  }

  /** A short-lived playback URL, or null when the note is gone (expired, or
   * not the caller's to read). Both lookups run as the caller: RLS on
   * messages and on the bucket decide, not this method. */
  async signVoiceUrl(messageId: string, expiresInSeconds = VOICE_URL_TTL_SECONDS): Promise<string | null> {
    const { data: message, error } = await this.db
      .from("messages")
      .select("audio_path, audio_deleted_at")
      .eq("id", messageId)
      .maybeSingle();
    if (error) throw error;
    if (!message?.audio_path || message.audio_deleted_at) return null;

    const { data } = await this.db.storage.from(VOICE_NOTES_BUCKET).createSignedUrl(message.audio_path, expiresInSeconds);
    return data?.signedUrl ?? null;
  }

  /** Who a broadcast can reach. Only actively coached clients can be
   * messaged at all (RLS), so "all" is every active client and "subscribed"
   * narrows that to an unexpired, unfrozen subscription. */
  async listBroadcastRecipients(now: Date): Promise<Record<BroadcastAudience, string[]>> {
    const { data, error } = await this.db
      .from("coach_client_roster")
      .select("client_id, subscription_status, subscription_end_date")
      .eq("status", "active");
    if (error) throw error;
    const all = data.map((row) => row.client_id as string);
    const subscribed = data
      .filter(
        (row) =>
          row.subscription_status != null &&
          subscriptionDisplayStatus(
            { status: row.subscription_status as ClientSubscriptionStatus, end_date: row.subscription_end_date! },
            now,
          ) === "active",
      )
      .map((row) => row.client_id as string);
    return { all, subscribed };
  }

  /** Sends the same message to every listed client in a single bulk insert
   * (not a loop of single inserts) — used for coach-to-all-active-clients
   * broadcasts. Callers don't need the created rows back. */
  async broadcast(coachId: string, clientIds: string[], body: string): Promise<void> {
    const { error } = await this.db.from("messages").insert(
      clientIds.map((clientId) => ({
        coach_id: coachId,
        client_id: clientId,
        sender_role: "coach" as const,
        body,
      })),
    );
    if (error) throw error;
  }

  /** Marks every message in the thread NOT sent by the caller as read —
   * the caller passes their own role so they never mark their own
   * outgoing messages read. */
  async markThreadRead(clientId: string, readerRole: "coach" | "client"): Promise<void> {
    const otherRole = readerRole === "coach" ? "client" : "coach";
    const { error } = await this.db
      .from("messages")
      .update({ read_at: new Date().toISOString() })
      .eq("client_id", clientId)
      .eq("sender_role", otherRole)
      .is("read_at", null);
    if (error) throw error;
  }
}
